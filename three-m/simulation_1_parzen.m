close all;
rng(1);
h = 1;
xi = rand(1,1024);
x = linspace(-1,2,1024);
p = sum(abs(bsxfun(@minus,x(:),xi(:)')) <= h/2,2)/(numel(xi)*h);
figure('Color','w','Position',[100 100 1100 420]);
subplot(1,2,1);
plot(x,p,'b-','LineWidth',1.5);
xlabel('x');
ylabel('估计密度');
title('均匀随机样本');
