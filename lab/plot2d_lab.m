clear;
clc;
close all;
x = linspace(0,2*pi,201);
y1 = sin(x);
y2 = cos(x);
figure(1);
set(gcf,'Color','w','Position',[80 80 1000 720]);
subplot(2,2,1);
plot(y1,'b-','LineWidth',1.5);
title('单向量形式 plot(y)');
xlabel('样本序号'); ylabel('y'); grid on;
subplot(2,2,2);
plot(x,y1,'r--','LineWidth',1.5);
title('双向量形式 plot(x,y)');
xlabel('x'); ylabel('y'); grid on;
subplot(2,2,3);
plot(x,y1,'b-',x,y2,'r--','LineWidth',1.5);
title('多组数据形式');
xlabel('x'); ylabel('y'); grid on;
legend('sin(x)','cos(x)');
subplot(2,2,4);
Y = [y1' y2'];
plot(x,Y,'LineWidth',1.5);
title('矩阵形式 plot(x,Y)');
xlabel('x'); ylabel('y'); grid on;
legend('sin(x)','cos(x)');

figure(2);
set(gcf,'Color','w','Position',[100 100 900 600]);
plot(x,y1,'b-','LineWidth',1.5);
hold on;
plot(x,y2,'r--','LineWidth',1.5);
plot(x,y1+y2,'k-.','LineWidth',1.5);
hold off;
title('多次重叠绘制曲线');
xlabel('x'); ylabel('y'); grid on;
legend('sin(x)','cos(x)','sin(x)+cos(x)');
axis([0 2*pi -1.5 1.5]);

t = linspace(-2,2,201);
figure(3);
set(gcf,'Color','w','Position',[120 120 900 600]);
plot(t,t.^2,'b-','LineWidth',1.5);
title('多窗口绘制 窗口一');
xlabel('x'); ylabel('y'); grid on;
legend('y=x^2');
figure(4);
set(gcf,'Color','w','Position',[160 160 900 600]);
plot(t,t.^3,'r-','LineWidth',1.5);
title('多窗口绘制 窗口二');
xlabel('x'); ylabel('y'); grid on;
legend('y=x^3');

figure(5);
set(gcf,'Color','w','Position',[140 80 1000 720]);
subplot(2,2,1);
plot(x,y1,'b-','LineWidth',1.5);
title('子图一 sin(x)');
xlabel('x'); ylabel('y'); grid on;
subplot(2,2,2);
plot(x,y2,'r--','LineWidth',1.5);
title('子图二 cos(x)');
xlabel('x'); ylabel('y'); grid on;
subplot(2,2,3);
plot(x,sin(2*x),'m-.','LineWidth',1.5);
title('子图三 sin(2x)');
xlabel('x'); ylabel('y'); grid on;
subplot(2,2,4);
plot(x,cos(2*x),'k:','LineWidth',1.5);
title('子图四 cos(2x)');
xlabel('x'); ylabel('y'); grid on;

figure(6);
set(gcf,'Color','w','Position',[180 120 900 600]);
plot(x,y1,'b-',x,y2,'r--','LineWidth',1.5);
axis([0 2*pi -1.2 1.2]);
set(gca,'XTick',[0 pi/2 pi 3*pi/2 2*pi]);
set(gca,'XTickLabel',{'0','pi/2','pi','3pi/2','2pi'});
set(gca,'YTick',-1:0.5:1);
title('坐标刻度设置');
xlabel('x 弧度'); ylabel('y'); grid on;
legend('sin(x)','cos(x)');
